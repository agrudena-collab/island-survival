"""Generates scripts/build_review_model.luau from data/rig_manifest.json (the Studio assembly uses the numbers of the actually built mesh).
usage: python gen_assembly.py <package_dir>"""
import json
import os
import sys

pkg = sys.argv[1]
rig = json.load(open(os.path.join(pkg, "data", "rig_manifest.json")))
c = rig["part_bbox_centres_blender"]


def v3(p):
    """Blender (x, y, z) -> Roblox model position (-x, z, y)"""
    return "%.6f, %.6f, %.6f" % (p[0], p[1], p[2])


src = '''--!nocheck
-- BusinessDad_Review: reproducible Studio assembly of the review model (static pose, Phone prop in the left hand).
-- GENERATED by scripts/gen_assembly.py from data/rig_manifest.json.
-- Run in the Studio command bar of a CLEAN place (Rojo disconnected) after importing the two FBX files with the 3D Importer
-- (Scale Unit Stud, factor 1, World Forward Front / Up Top, "Upload to Roblox" unchecked):
--   export/BusinessDad_Body.fbx   -> model "BusinessDad_Body"
--   export/BusinessDad_Props.fbx  -> model "BusinessDad_Props"
-- Result: Workspace.BusinessDad_Review with Phone (PhoneGrip weld LeftHand -> Phone). No PoseController / pose folders: the model is static.
-- Blender (x,y,z) = (X,-F,H) -> Roblox model position (-x, z, y).
local ws = workspace
local m = ws:FindFirstChild("BusinessDad_Body")
local wrap = ws:FindFirstChild("BusinessDad_Props")
assert(m and wrap, "import both FBX files first")

local function R(x, y, z)
	return Vector3.new(-x, z, y)
end

-- 1. placement: shift the imported body so that UpperTorso sits on the exact mapped bbox centre of the Blender mesh
local delta = m.UpperTorso.Position - R(%(ut)s)
m:TranslateBy(-delta)
print("BD placement delta", delta, "check Head", (m.Head.Position - R(%(hd)s)).Magnitude)

-- 2. prop: one MeshPart, ONE WeldConstraint (LeftHand -> Phone)
local p = nil
for _, d in ipairs(wrap:GetDescendants()) do
	if d:IsA("MeshPart") and string.find(d.Name, "Phone", 1, true) == 1 then
		p = d
	end
end
assert(p, "prop mesh missing: Phone")
p.Name = "Phone"
p.Parent = ws
p.CFrame = CFrame.new(R(%(ph)s))
p.Parent = m
p.Anchored = false
p.CanCollide = false
p.CanQuery = false
p.CanTouch = false
p.Massless = true
local w = Instance.new("WeldConstraint")
w.Name = "PhoneGrip"
w.Part0, w.Part1 = m.LeftHand, p
w.Parent = p
wrap:Destroy()
for _, d in ipairs(m:GetDescendants()) do
	if d:IsA("BasePart") then
		d.Anchored = false
	end
	if d:IsA("MeshPart") then
		d.Color = Color3.new(1, 1, 1) -- the atlas already carries the colours: a white tint avoids a double multiplication
	end
end
m.Name = "BusinessDad_Review"
print("BusinessDad_Review assembled")
''' % {"ut": v3(c["UpperTorso"]), "hd": v3(c["Head"]), "ph": v3(c["Phone"])}
open(os.path.join(pkg, "scripts", "build_review_model.luau"), "w", encoding="utf-8").write(src)
print("written", len(src))
