"""Generates scripts/build_review_model.luau from data/rig_manifest.json (the Studio assembly uses the numbers of the actually built mesh).
usage: python gen_assembly.py <package_dir>"""
import json
import os
import sys

pkg = sys.argv[1]
rig = json.load(open(os.path.join(pkg, "data", "rig_manifest.json")))
c = rig["part_bbox_centres_blender"]
J = rig["joints_blender"]
pc = open(os.path.join(pkg, "scripts", "PoseController.luau"), encoding="utf-8").read()
assert "]]" not in pc


def v3(p):
    """Blender (x, y, z) -> Roblox model position (-x, z, y)"""
    return "Vector3.new(%.7f, %.7f, %.7f)" % (-p[0], p[2], p[1])


src = '''--!nocheck
-- GymDad_Review_V2: reproducible Studio assembly of the review model (static HoldWeights pose, Dumbbell + GymBag props).
-- GENERATED by scripts/gen_assembly.py from data/rig_manifest.json.
-- Run in the Studio command bar of a CLEAN place (Rojo disconnected) after importing the two FBX files with the 3D Importer
-- (Scale Unit Stud, factor 1, World Forward Front / Up Top, "Upload to Roblox" unchecked):
--   export/GymDad_V2_Body.fbx   -> model "GymDad_V2_Body"
--   export/GymDad_V2_Props.fbx  -> model "GymDad_V2_Props"
-- Result: Workspace.GymDad_Review_V2 with Dumbbell (DumbbellGrip -> RightHand), GymBag (BagGrip -> LeftHand), HoldWeightsPose + NeutralPose folders, PoseController ModuleScript.
-- Blender (x,y,z) = (X,-F,H) -> Roblox model position (-x, z, y); after the placement below the model sits exactly on that mapping (soles on Y = 0, body axis X = 0).
local ws = workspace
local m = ws:FindFirstChild("GymDad_V2_Body")
local wrap = ws:FindFirstChild("GymDad_V2_Props")
assert(m and wrap, "import both FBX files first")
assert(not m:FindFirstChild("HoldWeightsPose"), "already assembled")

local function R(x, y, z)
	return Vector3.new(-x, z, y)
end

-- 1. placement: shift the imported body so that UpperTorso sits on the exact mapped bbox centre of the Blender mesh
local delta = m.UpperTorso.Position - R(%(ut)s)
m:TranslateBy(-delta)
print("GYM placement delta", delta, "check Head", (m.Head.Position - R(%(hd)s)).Magnitude)

-- 2. props: one MeshPart each, ONE WeldConstraint each (Dumbbell -> RightHand, GymBag -> LeftHand)
local function mount(name, centre, part0, weldName)
	local p = nil
	for _, d in ipairs(wrap:GetDescendants()) do
		if d:IsA("MeshPart") and string.find(d.Name, name, 1, true) == 1 then
			p = d
		end
	end
	assert(p, "prop mesh missing: " .. name)
	p.Name = name
	p.Parent = ws
	p.CFrame = CFrame.new(centre)
	p.Parent = m
	p.Anchored = false
	p.CanCollide = false
	p.CanQuery = false
	p.CanTouch = false
	p.Massless = true
	local w = Instance.new("WeldConstraint")
	w.Name = weldName
	w.Part0, w.Part1 = part0, p
	w.Parent = p
	return p
end
mount("Dumbbell", R(%(db)s), m.RightHand, "DumbbellGrip")
mount("GymBag", R(%(bg)s), m.LeftHand, "BagGrip")
wrap:Destroy()
for _, p in ipairs(m:GetDescendants()) do
	if p:IsA("BasePart") then
		p.Anchored = false
	end
	if p:IsA("MeshPart") then
		p.Color = Color3.new(1, 1, 1) -- the atlas already carries the colours: a white tint avoids a double multiplication
	end
end

-- 3. HoldWeightsPose = every part CFrame relative to HumanoidRootPart
local hrp = m.HumanoidRootPart
local function store(name, cfOf)
	local folder = Instance.new("Folder")
	folder.Name = name
	for _, p in ipairs(m:GetChildren()) do
		if p:IsA("BasePart") then
			local v = Instance.new("CFrameValue")
			v.Name = p.Name .. "_PartCFrame"
			v.Value = hrp.CFrame:ToObjectSpace(cfOf(p))
			v.Parent = folder
		end
	end
	folder.Parent = m
end
store("HoldWeightsPose", function(p)
	return p.CFrame
end)

-- 4. NeutralPose (QA control pose): both arms rigidly swung straight down about the joints (bone lengths unchanged), hands and props follow the forearms
local function rotTo(a, b)
	a, b = a.Unit, b.Unit
	local axis = a:Cross(b)
	local dot = math.clamp(a:Dot(b), -1, 1)
	if axis.Magnitude < 1e-7 then
		if dot > 0 then
			return CFrame.new()
		end
		local perp = math.abs(a.X) < 0.9 and Vector3.xAxis or Vector3.yAxis
		return CFrame.fromAxisAngle(a:Cross(perp).Unit, math.pi)
	end
	return CFrame.fromAxisAngle(axis.Unit, math.acos(dot))
end
local DOWN = Vector3.new(0, -1, 0)
local J = {
	RightShoulder = %(rs)s, RightElbow = %(re)s, RightWrist = %(rw)s,
	LeftShoulder = %(ls)s, LeftElbow = %(le)s, LeftWrist = %(lw)s,
}
local T = {}
for _, side in ipairs({ "Right", "Left" }) do
	local S, E, W = J[side .. "Shoulder"], J[side .. "Elbow"], J[side .. "Wrist"]
	local Ru = rotTo(E - S, DOWN)
	local Tu = CFrame.new(S) * Ru * CFrame.new(-S)
	local E2 = Tu * E
	local Rl = rotTo((Tu * W) - E2, DOWN)
	local Tl = CFrame.new(E2) * Rl * CFrame.new(-E2) * Tu
	T[side .. "UpperArm"] = Tu
	T[side .. "LowerArm"] = Tl
	T[side .. "Hand"] = Tl
end
T.Dumbbell = T.RightHand
T.GymBag = T.LeftHand
store("NeutralPose", function(p)
	local t = T[p.Name]
	return t and (t * p.CFrame) or p.CFrame
end)

-- 5. PoseController inside the model, final name
local mod = Instance.new("ModuleScript")
mod.Name = "PoseController"
mod.Source = [[%(pc)s]]
mod.Parent = m
m.Name = "GymDad_Review_V2"
print("GymDad_Review_V2 assembled")
''' % {"ut": ", ".join("%.6f" % x for x in c["UpperTorso"]), "hd": ", ".join("%.6f" % x for x in c["Head"]), "db": ", ".join("%.6f" % x for x in c["Dumbbell"]),
       "bg": ", ".join("%.6f" % x for x in c["GymBag"]), "rs": v3(J["RightShoulder"]), "re": v3(J["RightElbow"]), "rw": v3(J["RightWrist"]),
       "ls": v3(J["LeftShoulder"]), "le": v3(J["LeftElbow"]), "lw": v3(J["LeftWrist"]), "pc": pc}
open(os.path.join(pkg, "scripts", "build_review_model.luau"), "w", encoding="utf-8").write(src)
print("written", len(src))
