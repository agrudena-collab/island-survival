"""Generates scripts/build_review_model.luau from data/rig_manifest.json + data/construction_spec.json (the Studio assembly uses the numbers of the actually built mesh).
usage: python gen_assembly.py <package_dir>"""
import json
import os
import sys

pkg = sys.argv[1]
rig = json.load(open(os.path.join(pkg, "data", "rig_manifest.json")))
spec = json.load(open(os.path.join(pkg, "data", "construction_spec.json")))
c = rig["part_bbox_centres_logical"]
J = spec["joints"]
pc = open(os.path.join(pkg, "scripts", "PoseController.luau"), encoding="utf-8").read()
assert "]]" not in pc


def v3(p):
    """logical (X,D,H) -> Roblox model position (-X, H, D)"""
    return "Vector3.new(%.7f, %.7f, %.7f)" % (-p[0], p[2], p[1])


def joint(n):
    return v3(J[n])


src = '''--!nocheck
-- GamerDad_Sweatshirt_Review: reproducible Studio assembly of the review model (static HoldCan pose, Headset + EnergyCan props).
-- GENERATED by scripts/gen_assembly.py from data/rig_manifest.json + data/construction_spec.json.
-- Run in the Studio command bar of a CLEAN place (Rojo disconnected) after importing the two FBX files with the 3D Importer
-- (Scale Unit Stud, factor 1, "Upload to Roblox" unchecked):
--   export/GamerDad_R15.fbx    -> model "GamerDad_R15"
--   export/GamerDad_Props.fbx  -> model "GamerDad_Props"
-- Result: Workspace.GamerDad_R15 with Headset (HeadsetMount -> Head), EnergyCan (CanGrip -> RightHand), HoldCanPose + NeutralPose folders, PoseController ModuleScript.
-- Logical (X,D,H) -> Roblox model position (-X, H, D); after the placement below the model sits exactly on that mapping (soles on Y = 0, body axis X = 0).
local ws = workspace
local m = ws:FindFirstChild("GamerDad_R15")
local wrap = ws:FindFirstChild("GamerDad_Props")
assert(m and wrap, "import both FBX files first")
assert(not m:FindFirstChild("HoldCanPose"), "already assembled")

local function R(x, d, h)
	return Vector3.new(-x, h, d)
end

-- 1. placement: the importer puts the body anywhere; shift it so that UpperTorso sits on the exact mapped bbox centre of the Blender mesh
local delta = m.UpperTorso.Position - R(%(ut)s)
m:TranslateBy(-delta)
print("GD placement delta", delta, "check Head", (m.Head.Position - R(%(hd)s)).Magnitude)

-- 2. props: one MeshPart each, ONE WeldConstraint each (Headset -> Head, EnergyCan -> RightHand)
local function mount(name, centre, part0, weldName)
	local p = nil
	for _, d in ipairs(wrap:GetDescendants()) do
		if d:IsA("MeshPart") and string.find(d.Name, name, 1, true) == 1 then
			p = d
		end
	end
	assert(p, "prop mesh missing: " .. name)
	p.Name = name
	p.Parent = ws
	p.CFrame = CFrame.new(centre)
	p.Parent = m
	p.Anchored = false
	p.CanCollide = false
	p.CanQuery = false
	p.CanTouch = false
	p.Massless = true
	local w = Instance.new("WeldConstraint")
	w.Name = weldName
	w.Part0, w.Part1 = part0, p
	w.Parent = p
	return p
end
mount("Headset", R(%(hs)s), m.Head, "HeadsetMount")
mount("EnergyCan", R(%(cn)s), m.RightHand, "CanGrip")
wrap:Destroy()
for _, p in ipairs(m:GetDescendants()) do
	if p:IsA("BasePart") then
		p.Anchored = false
	end
	if p:IsA("MeshPart") then
		p.Color = Color3.new(1, 1, 1) -- the atlas already carries the colours: a white tint avoids a double multiplication
	end
end

-- 3. HoldCanPose = every part CFrame relative to HumanoidRootPart
local hrp = m.HumanoidRootPart
local function store(name, cfOf)
	local folder = Instance.new("Folder")
	folder.Name = name
	for _, p in ipairs(m:GetChildren()) do
		if p:IsA("BasePart") then
			local v = Instance.new("CFrameValue")
			v.Name = p.Name .. "_PartCFrame"
			v.Value = hrp.CFrame:ToObjectSpace(cfOf(p))
			v.Parent = folder
		end
	end
	folder.Parent = m
end
store("HoldCanPose", function(p)
	return p.CFrame
end)

-- 4. NeutralPose (QA control pose): both arms rigidly swung straight down about the joints (bone lengths unchanged), hand / can follow the forearm
local function rotTo(a, b)
	a, b = a.Unit, b.Unit
	local axis = a:Cross(b)
	local dot = math.clamp(a:Dot(b), -1, 1)
	if axis.Magnitude < 1e-7 then
		if dot > 0 then
			return CFrame.new()
		end
		local perp = math.abs(a.X) < 0.9 and Vector3.xAxis or Vector3.yAxis
		return CFrame.fromAxisAngle(a:Cross(perp).Unit, math.pi)
	end
	return CFrame.fromAxisAngle(axis.Unit, math.acos(dot))
end
local DOWN = Vector3.new(0, -1, 0)
local J = {
	RightShoulder = %(rs)s, RightElbow = %(re)s, RightWrist = %(rw)s,
	LeftShoulder = %(ls)s, LeftElbow = %(le)s, LeftWrist = %(lw)s,
}
local T = {}
for _, side in ipairs({ "Right", "Left" }) do
	local S, E, W = J[side .. "Shoulder"], J[side .. "Elbow"], J[side .. "Wrist"]
	local Ru = rotTo(E - S, DOWN)
	local Tu = CFrame.new(S) * Ru * CFrame.new(-S)
	local E2 = Tu * E
	local Rl = rotTo((Tu * W) - E2, DOWN)
	local Tl = CFrame.new(E2) * Rl * CFrame.new(-E2) * Tu
	T[side .. "UpperArm"] = Tu
	T[side .. "LowerArm"] = Tl
	T[side .. "Hand"] = Tl
end
T.EnergyCan = T.RightLowerArm
T.EnergyCan = T.RightHand
store("NeutralPose", function(p)
	local t = T[p.Name]
	return t and (t * p.CFrame) or p.CFrame
end)

-- 5. PoseController inside the model
local mod = Instance.new("ModuleScript")
mod.Name = "PoseController"
mod.Source = [[%(pc)s]]
mod.Parent = m
print("GamerDad_Sweatshirt_Review assembled")
''' % {"ut": ", ".join("%.6f" % x for x in c["UpperTorso"]), "hd": ", ".join("%.6f" % x for x in c["Head"]), "hs": ", ".join("%.6f" % x for x in c["Headset"]),
       "cn": ", ".join("%.6f" % x for x in c["EnergyCan"]), "rs": joint("RightShoulder"), "re": joint("RightElbow"), "rw": joint("RightWrist"),
       "ls": joint("LeftShoulder"), "le": joint("LeftElbow"), "lw": joint("LeftWrist"), "pc": pc}
open(os.path.join(pkg, "scripts", "build_review_model.luau"), "w", encoding="utf-8").write(src)
print("written", len(src))
