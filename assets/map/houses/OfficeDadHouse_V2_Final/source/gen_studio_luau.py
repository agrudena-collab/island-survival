def lua(v, ind=0):
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if v is None:
        return 'nil'
    if isinstance(v, (int, float)):
        return repr(round(v, 4)) if isinstance(v, float) else str(v)
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, (list, tuple)):
        if all(isinstance(x, (int, float)) and not isinstance(x, bool) for x in v):
            return '{' + ','.join(lua(x) for x in v) + '}'
        return '{' + ','.join(lua(x) for x in v) + '}'
    if isinstance(v, dict):
        return '{' + ','.join('[%s]=%s' % (json.dumps(k), lua(x)) for k, x in v.items()) + '}'
    raise TypeError(type(v))


doors = [d for d in inter['doors'] if d['kind'] != 'hide']
hides = [d for d in inter['doors'] if d['kind'] == 'hide']
slim = lambda d: {k: d[k] for k in ('id', 'kind', 'axis', 'ctr', 'w', 'y0', 'h', 'wall', 'inside', 'locked', 'item', 'hinge_side', 'hinge_pt', 'centre', 'size', 'open_deg')}
data = {
    'doors': [slim(d) for d in doors],
    'hides': [slim(d) for d in hides],
    'anchors': inter['anchors'],
    'cover': inter['cover'],
    'routes': inter['routes'],
    'lights': inter['lights'],
    'box': coll['house'],
    'yard': yard['house'],
}

HEADER = '''--!nocheck
-- OfficeDadHouse_V2_Final -- Studio command-bar script (Edit mode). GENERATED by source/gen_studio_luau.py from data/*.json.
-- 1. Import export/OfficeDadHouse_V2_Final.fbx (Upload to Roblox OFF, vertex colours) and put the meshes into Workspace.OfficeDadHouse_V2_Final.RDH_House
--    (the root Model must exist; create it as an empty Model if needed). G_* chunks: set Transparency 0.7; N_* chunks: Material Neon.
-- 2. Put the father model (reference/OfficeDad_Final/model/OfficeDad_Final.rbxm) into Workspace and keep its name; this script moves a copy to the office window.
-- 3. Run this script. It is idempotent: it rebuilds RDH_Collision, RDH_RoomLights, Interactive, FamilyRoutes, LowCover, FamilyLotBounds, CaughtSpawn.
-- Coordinates are the plot coordinates of the generator (x east, y up, z toward the back yard; street at z < 0); the Blender -> FBX export keeps them 1:1.
-- NOT RUN IN STUDIO by the author of this file: see README_RU.md "не проверено".
local DATA = %s
local S = SCALE_PLACEHOLDER -- world scale of the export (ODH_SCALE)
'''

BODY = r'''
local CS = game:GetService("CollectionService")
local root = workspace:FindFirstChild("OfficeDadHouse_V2_Final")
if not root then
	root = Instance.new("Model")
	root.Name = "OfficeDadHouse_V2_Final"
	root.Parent = workspace
end

local function fresh(name, class)
	local old = root:FindFirstChild(name)
	if old then
		old:Destroy()
	end
	local o = Instance.new(class or "Folder")
	o.Name = name
	o.Parent = root
	return o
end

local function marker(name, pos, size, parent)
	local p = Instance.new("Part")
	p.Name, p.Anchored, p.CanCollide, p.CanQuery, p.CanTouch, p.Transparency = name, true, false, false, false, 1
	p.Size, p.Position, p.Parent = size, pos, parent
	return p
end

local function solid(name, cf, size, parent)
	local p = Instance.new("Part")
	p.Name, p.Anchored, p.CanCollide, p.CanTouch, p.Transparency = name, true, true, false, 1
	p.Size, p.CFrame, p.Parent = size, cf, parent
	return p
end

local function colour(r, g, b)
	return Color3.fromRGB(r, g, b)
end

-- 1. meshes collide with their exact shape (no invisible hulls), full render detail at any distance (no grass/detail popping);
--    RDH_Collision below adds clean boxes for floors, walls and stairs on top of it
local function precise(p)
	p.Anchored, p.CanTouch, p.CanCollide = true, false, true
	if p:IsA("MeshPart") then
		p.CollisionFidelity = Enum.CollisionFidelity.PreciseConvexDecomposition
		p.RenderFidelity = Enum.RenderFidelity.Precise
		p.DoubleSided = false
	end
end
local house = root:FindFirstChild("RDH_House")
if house then
	for _, p in ipairs(house:GetDescendants()) do
		if p:IsA("BasePart") then
			precise(p)
			if string.sub(p.Name, 1, 2) == "G_" then
				p.Transparency = 0.7
			elseif string.sub(p.Name, 1, 2) == "N_" then
				p.Material = Enum.Material.Neon
			end
		end
	end
end

-- 2. collision: merged solid boxes (walls, floors, stairs, frames, big furniture) + yard colliders (fence, trunks, shed, car)
local col = fresh("RDH_Collision")
for i, b in ipairs(DATA.box) do
	local x0, x1, h0, h1, z0, z1 = b[1], b[2], b[3], b[4], b[5], b[6]
	solid("B" .. i, CFrame.new((x0 + x1) / 2, (h0 + h1) / 2, (z0 + z1) / 2), Vector3.new(x1 - x0, h1 - h0, z1 - z0), col)
end
for i, y in ipairs(DATA.yard) do
	if y[1] == "box" then
		solid("Y" .. i, CFrame.new(y[2], y[6] / 2, y[3]), Vector3.new(y[4], y[6], y[5]), col)
	elseif y[1] == "cyl" then
		local p = solid("Y" .. i, CFrame.new(y[2], y[5] / 2, y[3]) * CFrame.Angles(0, 0, math.rad(90)), Vector3.new(y[5], y[4] * 2, y[4] * 2), col)
		p.Shape = Enum.PartType.Cylinder
	elseif y[1] == "fence" then
		local a, b2 = Vector3.new(y[2], 0, y[3]), Vector3.new(y[4], 0, y[5])
		local len = (b2 - a).Magnitude
		if len > 0.1 then
			solid("Y" .. i, CFrame.lookAt((a + b2) / 2 + Vector3.new(0, 2.5 * S, 0), b2 + Vector3.new(0, 2.5 * S, 0)), Vector3.new(0.6 * S, 5 * S, len), col)
		end
	end
end
-- hidden half step before the lowest stair tread (without it the navmesh has no step into the staircase)
do
	local a = DATA.anchors.stair_foot
	local p = solid("StairFootStep", CFrame.new(a[1], a[2] + 0.25 * S, a[3] - 1.15 * S), Vector3.new(2.4 * S, 0.5 * S, 1.7 * S), col)
	p.CanQuery = true
end

-- 3. room lights
local lights = fresh("RDH_RoomLights")
for _, l in ipairs(DATA.lights) do
	local p = marker("Light_" .. l[1], Vector3.new(l[2], l[3], l[4]), Vector3.new(0.5, 0.5, 0.5), lights)
	local pl = Instance.new("PointLight")
	pl.Brightness, pl.Range, pl.Color, pl.Shadows = 1.6, 34 * S, colour(255, 235, 200), false
	pl.Parent = p
end

-- 4. interactive layer
local inter = fresh("Interactive")
local function leaf(model, name, d, colourRgb)
	local p = Instance.new("Part")
	p.Name, p.Anchored, p.CanCollide, p.CanTouch, p.CanQuery = name, true, true, false, true
	p.Size = Vector3.new(d.size[1], d.size[2], d.size[3])
	p.Material, p.Color = Enum.Material.Wood, colourRgb
	local cf = CFrame.new(d.centre[1], d.centre[2], d.centre[3])
	p.CFrame = cf
	p:SetAttribute("Hinge", Vector3.new(d.hinge_pt[1], d.hinge_pt[2], d.hinge_pt[3]))
	p:SetAttribute("OpenAngle", d.open_deg)
	p:SetAttribute("ClosedCFrame", cf)
	local pm = Instance.new("PathfindingModifier")
	pm.PassThrough = true
	pm.Parent = p
	p.Parent = model
	return p
end

local function prompt(parent, text, dist)
	local pp = Instance.new("ProximityPrompt")
	pp.ActionText, pp.ObjectText, pp.HoldDuration, pp.MaxActivationDistance, pp.RequiresLineOfSight = text, "", 0, dist or 9, false
	pp.Parent = parent
	return pp
end

for _, d in ipairs(DATA.doors) do
	local m = Instance.new("Model")
	m.Name = "Door_" .. d.id
	local c = (d.kind == "front" or d.kind == "back" or d.kind == "service" or d.kind == "balcony") and colour(122, 86, 56) or colour(154, 118, 80)
	leaf(m, "Leaf", d, c)
	local pr = marker("PromptPart", Vector3.new(d.centre[1], d.centre[2], d.centre[3]), Vector3.new(1, 1, 1) * S, m)
	pr.CanQuery = true
	prompt(pr, "Открыть / закрыть", 9 * S)
	m:SetAttribute("DoorId", d.id)
	m:SetAttribute("Open", false)
	m:SetAttribute("LockedFromOutside", d.locked == true)
	if d.item then
		m:SetAttribute("RequiresItem", d.item)
	end
	m:SetAttribute("InsideDir", Vector3.new(d.inside[1], 0, d.inside[2]))
	m.PrimaryPart = pr
	m.Parent = inter
	CS:AddTag(m, "HouseDoor")
end

local A = DATA.anchors
local function pt(name, a, size, parent, lookFrom)
	local p = marker(name, Vector3.new(a[1], a[2] + 0.1, a[3]), size, parent)
	p.CFrame = CFrame.lookAt(p.Position, p.Position + Vector3.new(a[4], 0, a[5]))
	return p
end
for _, d in ipairs(DATA.hides) do
	local key = string.sub(d.id, 6) -- hide_wardrobe -> wardrobe
	local m = Instance.new("Model")
	m.Name = "HideSpot_" .. key
	leaf(m, "Leaf", d, colour(162, 123, 84))
	pt("HidePoint", A["hide_" .. key .. "_hide"], Vector3.new(1, 0.2, 1) * S, m)
	pt("ExitPoint", A["hide_" .. key .. "_exit"], Vector3.new(1, 0.2, 1) * S, m)
	local ep = pt("EnterPart", A["hide_" .. key .. "_enter"], Vector3.new(4, 5, 4) * S, m)
	ep.CanQuery = true
	prompt(ep, "Спрятаться", 9 * S)
	local ip = pt("InsidePart", A["hide_" .. key .. "_inside"], Vector3.new(3, 5, 3) * S, m)
	ip.CanQuery = true
	prompt(ip, "Выйти", 9 * S)
	m:SetAttribute("SpotId", key)
	m.Parent = inter
	CS:AddTag(m, "HideSpot")
end

-- work pass of the father: lies on the dashboard of the car on the driveway; a SpareKey part sets HasSpareKey
-- (the hint text of HouseInteractionService still says "Запасной ключ взят": ТРЕБУЕТСЯ ПРАВКА src, see README_RU.md)
do
	local a = A.work_pass
	local pass = Instance.new("Part")
	pass.Name, pass.Anchored, pass.CanCollide, pass.CanTouch, pass.CanQuery = "WorkPass", true, false, false, true
	pass.Size = Vector3.new(0.95, 0.1, 1.35) * S
	pass.Color, pass.Material = colour(244, 243, 238), Enum.Material.SmoothPlastic
	pass.CFrame = CFrame.new(a[1], a[2], a[3])
	pass.Parent = inter
	local band = Instance.new("Part")
	band.Name, band.Anchored, band.CanCollide, band.CanTouch, band.CanQuery = "Band", true, false, false, false
	band.Size, band.Color, band.CFrame = Vector3.new(0.95, 0.11, 0.3) * S, colour(43, 58, 92), pass.CFrame * CFrame.new(0, 0.01 * S, -0.45 * S)
	band.Parent = pass
	local photo = Instance.new("Part")
	photo.Name, photo.Anchored, photo.CanCollide, photo.CanTouch, photo.CanQuery = "Photo", true, false, false, false
	photo.Size, photo.Color, photo.CFrame = Vector3.new(0.3, 0.11, 0.4) * S, colour(232, 181, 140), pass.CFrame * CFrame.new(0, 0.01 * S, 0.2 * S)
	photo.Parent = pass
	prompt(pass, "Взять пропуск", 10 * S)
	CS:AddTag(pass, "SpareKey")
end

-- ladder spot under the balcony of the office (path B)
do
	local top, foot = A.ladder_top, A.ladder_foot
	local m = Instance.new("Model")
	m.Name = "BalconyLadder"
	local spot = marker("SpotPart", Vector3.new(foot[1], 1.0 * S, foot[3] + 0.5 * S), Vector3.new(4.4, 2, 2.6) * S, m)
	spot.CanQuery = true
	prompt(spot, "Приставить лестницу", 10 * S)
	local ladder = Instance.new("Model")
	ladder.Name = "Ladder"
	ladder.Parent = m
	local a0, a1 = Vector3.new(foot[1], 0.2 * S, foot[3] - 0.2 * S), Vector3.new(top[1], top[2] + 2.2 * S, top[3] + 0.6 * S)
	local mid, len = (a0 + a1) / 2, (a1 - a0).Magnitude
	for _, sx in ipairs({ -1.2 * S, 1.2 * S }) do
		local r = Instance.new("Part")
		r.Name, r.Anchored, r.CanCollide, r.CanTouch, r.Material, r.Color = "Rail", true, false, false, Enum.Material.Metal, colour(190, 197, 202)
		r.Size = Vector3.new(0.35, 0.35, len) * 1.0
		r.CFrame = CFrame.lookAt(mid + Vector3.new(sx, 0, 0), a1 + Vector3.new(sx, 0, 0))
		r.Parent = ladder
	end
	local n = math.floor(len / (1.2 * S))
	for k = 1, n - 1 do
		local c = a0:Lerp(a1, k / n)
		local rung = Instance.new("Part")
		rung.Name, rung.Anchored, rung.CanCollide, rung.CanTouch, rung.Material, rung.Color = "Rung", true, false, false, Enum.Material.Metal, colour(190, 197, 202)
		rung.Size, rung.CFrame = Vector3.new(2.4 * S, 0.25, 0.25), CFrame.new(c)
		rung.Parent = ladder
	end
	local truss = Instance.new("TrussPart")
	truss.Name, truss.Anchored, truss.CanCollide, truss.Transparency = "ClimbTruss", true, true, 1
	truss.Size = Vector3.new(2 * S, top[2] + 1.2 * S, 2 * S)
	truss.CFrame = CFrame.new(foot[1], (top[2] + 1.2 * S) / 2, foot[3] - 1.0 * S)
	truss.Parent = m
	m.Parent = inter
	CS:AddTag(m, "LadderSpot")
end

-- 5. family data
local routes = fresh("FamilyRoutes")
local dogs = fresh("DogRoutes") -- the service knows only Wife and Son: dog points are kept apart (ТРЕБУЕТСЯ ПРАВКА src for a dog)
for _, r in ipairs(DATA.routes) do
	local parent = (r.role == "Dog") and dogs or routes
	local p = marker(string.format("%s_%02d", r.role, r.i), Vector3.new(r.x, r.y + 0.1, r.z), Vector3.new(1, 0.2, 1), parent)
	p:SetAttribute("Pause", r.pause or 0)
	if r.activity then
		p:SetAttribute("Activity", r.activity)
	end
end
local cov = fresh("LowCover")
for i, c in ipairs(DATA.cover) do
	local p = Instance.new("Part")
	p.Name = string.format("%s_%02d", c.name, i)
	p.Anchored, p.CanCollide, p.CanTouch, p.CanQuery, p.Transparency = true, false, false, true, 1
	p.Size = Vector3.new(c.w, c.h, c.d)
	p.CFrame = CFrame.new(c.x, c.y + c.h / 2, c.z) * CFrame.Angles(0, -c.yaw, 0)
	p:SetAttribute("CoverHeight", c.h)
	p.Parent = cov
end
for _, n in ipairs({ "FamilyLotBounds", "CaughtSpawn" }) do
	local o = root:FindFirstChild(n)
	if o then
		o:Destroy()
	end
end
marker("FamilyLotBounds", Vector3.new(52 * S, 30 * S, 50 * S), Vector3.new(104 * S, 60 * S, 100 * S), root)
do
	local a = A.caught_spawn
	marker("CaughtSpawn", Vector3.new(a[1], a[2], a[3]), Vector3.new(4, 0.2, 4) * S, root)
end

-- 6. the father (OfficeDad_Final stays as it is): standing at the office window with the briefcase, Anchored
local src = workspace:FindFirstChild("OfficeDad_Final") or root:FindFirstChild("OfficeDad_Father")
if src then
	local f = src
	if f.Parent ~= root then
		f = src:Clone()
		f.Parent = root
	end
	f.Name = "OfficeDad_Father"
	local a = A.father
	f:PivotTo(CFrame.lookAt(Vector3.new(a[1], a[2] + 3.0, a[3]), Vector3.new(a[1], a[2] + 3.0, a[3] + 10)))
	for _, p in ipairs(f:GetDescendants()) do
		if p:IsA("BasePart") then
			p.Anchored = true
		end
	end
	CS:AddTag(f, "FamilyFather")
	f:SetAttribute("DadId", "OfficeDad")
else
	warn("OfficeDad_Final not found: place the father model, then run again")
end
CS:AddTag(root, "FamilyHouse")
print("OfficeDadHouse_V2_Final: family data applied")
'''

open(os.path.join(S, 'apply_office_dad_house.luau'), 'w', encoding='utf-8').write((HEADER % lua(data)).replace('SCALE_PLACEHOLDER', SCS) + BODY)

